#ifndef ANF_FG_H
#define ANF_FG_H

#include "anf_types.h"

/*******************************************************************************************************************************
*   @brief
*       Frame generation technique group create info
*******************************************************************************************************************************/
struct AnfFGCreateInfo
{
    AnfStructHeader             header;             ///< Standard struct header

    AnfDim2D                    inputSize;          ///< The size of the input resources. The output resources must match size.
};

/*******************************************************************************************************************************
*   @brief
*       Frame generation dispatch information
*******************************************************************************************************************************/
struct AnfFGDispatch
{
    AnfStructHeader                  header;                     ///< Standard struct header
};

/*******************************************************************************************************************************
*   @brief
*       Frame generation technique requirements
*******************************************************************************************************************************/
struct AnfFGRequirements
{
    AnfStructHeader                  header;                     ///< Standard struct header
};

#endif // ANF_FG_H